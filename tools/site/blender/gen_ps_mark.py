# Makes ps_mark.py, the PlayStation mark as the fat's badge is cut: the four colours as exact Bezier outlines, and the black
# emblem they sit on, which on a real console follows the mark's silhouette with a border about 1 mm wide.
#   python gen_ps_mark.py <the mark as an svg> ps_mark.py
# It needs shapely, on the PC, not in Blender. The result is plain data, and Blender needs nothing but that.
import json
import re
import sys

from shapely.geometry import Polygon
from shapely.ops import unary_union

BORDER_MM = 0.95   # the emblem's border, from close-ups of an SCPH-30001 at about 10 px to the mm
WIDTH_MM = 10.6    # the mark's own width on that console


def parse(d):
    """Subpaths of an absolute M/L/C/z path, each a list of cubic segments (p0, c1, c2, p1)."""
    tokens = re.findall(r'[MLCz]|-?\d+\.?\d*(?:[eE][-+]?\d+)?', d)
    i = 0
    subs, segs, at = [], [], None

    def xy():
        nonlocal i
        x, y = float(tokens[i]), float(tokens[i + 1])
        i += 2
        return x, y

    cmd = None
    while i < len(tokens):
        if tokens[i] in 'MLCz':
            cmd = tokens[i]
            i += 1
            if cmd == 'z':
                if segs:
                    subs.append(segs)
                segs = []
                continue
        if cmd == 'M':
            at = xy()
            cmd = 'L'
        elif cmd == 'L':
            p = xy()
            if p != at:
                segs.append((at, (at[0] + (p[0] - at[0]) / 3, at[1] + (p[1] - at[1]) / 3), (at[0] + (p[0] - at[0]) * 2 / 3, at[1] + (p[1] - at[1]) * 2 / 3), p))
            at = p
        elif cmd == 'C':
            c1, c2, p = xy(), xy(), xy()
            segs.append((at, c1, c2, p))
            at = p
    if segs:
        subs.append(segs)
    return subs


def sample(segs, n=24):
    pts = []
    for p0, c1, c2, p1 in segs:
        for j in range(n):
            t = j / n
            u = 1 - t
            pts.append(tuple(u * u * u * p0[k] + 3 * u * u * t * c1[k] + 3 * u * t * t * c2[k] + t * t * t * p1[k] for k in (0, 1)))
    return pts


def main():
    svg = open(sys.argv[1], encoding='utf-8').read()
    layers = []
    for m in re.finditer(r'<path(.*?)/>', svg, re.S):
        attrs = m.group(1)
        d = ' '.join(re.search(r'\bd="([^"]*)"', attrs, re.S).group(1).split())
        layers.append((re.search(r'fill:(#[0-9a-f]{6})', attrs).group(1), parse(d)))

    pts = [q for _, subs in layers for segs in subs for s in segs for q in s]
    x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts)
    y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
    k = 1.0 / (x1 - x0)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2

    def norm(p):
        return (round((p[0] - cx) * k, 5), round((cy - p[1]) * k, 5))  # up is up, the width is 1

    colours = {}
    shapes = []
    for fill, subs in layers:
        out = []
        for segs in subs:
            n = len(segs)
            nodes = []
            for i in range(n):
                seg, before = segs[i], segs[(i - 1) % n]
                nodes.append((norm(seg[0]), norm(before[2]), norm(seg[1])))  # the point, its left and right handles
            out.append(nodes)
            poly = Polygon([norm(p) for p in sample(segs)]).buffer(0)
            shapes.append(poly)
        colours[fill] = out

    border = BORDER_MM / WIDTH_MM
    whole = unary_union(shapes).buffer(0.02).buffer(-0.02)
    body = whole.buffer(border + 0.05, quad_segs=24).buffer(-0.05, quad_segs=24)  # concave corners eased, as a die cuts them
    if body.geom_type != 'Polygon':
        body = max(body.geoms, key=lambda g: g.area)
    ring = list(Polygon(body.exterior).simplify(0.0012).exterior.coords)[:-1]

    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Generated by gen_ps_mark.py. The width of the mark is 1, centred, up is +. Each colour is a list of closed Bezier\n')
        f.write('# outlines, each node (point, left handle, right handle). BODY is the black emblem\'s outline.\n')
        f.write('COLOURS = ' + json.dumps(colours, separators=(',', ':')) + '\n')
        f.write('BODY = ' + json.dumps([(round(x, 5), round(y, 5)) for x, y in ring], separators=(',', ':')) + '\n')
    print('colours', {c: [len(n) for n in o] for c, o in colours.items()}, 'body points', len(ring), 'height', round((y1 - y0) * k, 3))


main()
